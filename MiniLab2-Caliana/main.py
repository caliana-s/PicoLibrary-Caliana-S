# main.py - Mini-Lab 2: Dynamic Office Nameplate
# Raspberry Pi Pico / Wokwi MicroPython
#
# Hardware assumptions based on the supplied circuit:
#   LCD: I2C0 SDA=GP0, SCL=GP1
#   NeoPixel ring: GP2, 8 LEDs
#   Passive buzzer: GP16
#   Previous button: GP10
#   Next button: GP11
#   Availability button: GP12
#
# Buttons are wired between their GPIO pin and GND. The Button library
# therefore uses its default lowActive=True (internal pull-up).
#
# If your Wokwi diagram uses different GPIO pins, change only the
# constants in this section.

import time
from machine import Pin

from Displays import LCDDisplay
from Button import Button
from Buzzer import PassiveBuzzer
from LightStrip import LightStrip
from Lights import RED, YELLOW, GREEN, BLACK


# ------------------------- PIN CONFIGURATION -------------------------

LCD_SDA = 0
LCD_SCL = 1

LIGHTSTRIP_PIN = 2
BUZZER_PIN = 16

PREVIOUS_BUTTON_PIN = 10
NEXT_BUTTON_PIN = 11
AVAILABILITY_BUTTON_PIN = 12

NUMBER_OF_LEDS = 8


# ------------------------- EMPLOYEE CLASSES --------------------------

class Employee:
    """Base employee class. Shared information and default behavior."""

    def __init__(self, name, phone, position, email, availability="Available"):
        self.name = name
        self.phone = phone
        self.position = position
        self.email = email
        self.availability = availability

    def get_details(self):
        return self.name + " - " + self.position

    def get_availability(self):
        return self.availability

    def cycle_availability(self):
        # Available -> Away -> Busy -> Available
        choices = ["Available", "Away", "Busy"]
        current = choices.index(self.availability)
        self.availability = choices[(current + 1) % len(choices)]


class Faculty(Employee):
    """Faculty members include courses and office hours."""

    def __init__(self, name, phone, position, email, courses, office_hours):
        super().__init__(name, phone, position, email, "Available")
        self.courses = courses
        self.office_hours = office_hours

    def get_details(self):
        return self.name + " | Faculty"

    def get_availability(self):
        return self.availability


class Staff(Employee):
    """Staff use the standard user-controlled availability."""

    def get_details(self):
        return self.name + " | Staff"


class StudentWorker(Employee):
    """Student workers include a supervisor."""

    def __init__(self, name, phone, position, email, supervisor):
        super().__init__(name, phone, position, email, "Available")
        self.supervisor = supervisor

    def get_details(self):
        return self.name + " | Student Worker"


class Administrator(Employee):
    """Administrator availability is generated by a simulated calendar."""

    def __init__(self, name, phone, position, email, calendar):
        super().__init__(name, phone, position, email, "Available")
        self.calendar = calendar

    def get_availability(self):
        # The calendar returns a status based on the current time.
        self.availability = self.calendar.get_availability()
        return self.availability

    def cycle_availability(self):
        # Administrator availability is automatic, not button-controlled.
        pass


class Calendar:
    """Simple simulated calendar for the administrator."""

    def __init__(self):
        self.statuses = ["Available", "Busy", "Away"]
        self.start_time = time.ticks_ms()

    def get_availability(self):
        # Change the calendar status every 10 seconds for the demo.
        elapsed = time.ticks_diff(time.ticks_ms(), self.start_time)
        index = (elapsed // 10000) % len(self.statuses)
        return self.statuses[int(index)]


# ------------------------- BUTTON HANDLER ----------------------------

class NameplateButtonHandler:
    """Button interrupts only set flags; display work happens in main loop."""

    def __init__(self):
        self.previous_pressed = False
        self.next_pressed = False
        self.availability_pressed = False

    def buttonPressed(self, name):
        if name == "previous":
            self.previous_pressed = True
        elif name == "next":
            self.next_pressed = True
        elif name == "availability":
            self.availability_pressed = True

    def buttonReleased(self, name):
        pass


# ------------------------- NAMEPLATE VIEW ----------------------------

class NameplateView:
    """Controls the LCD and status light ring."""

    def __init__(self, display, lightstrip):
        self.display = display
        self.lightstrip = lightstrip

    def show_employee(self, employee, page):
        self.display.clear()

        status = employee.get_availability()

        # Page 1: name and availability for every employee.
        if page == 0:
            self.display.showText(employee.name[:16], 0, 0)
            self.display.showText(status[:16], 1, 0)

        # Page 2: faculty show office hours and phone.
        elif isinstance(employee, Faculty):
            self.display.showText(employee.office_hours[:16], 0, 0)
            self.display.showText(employee.phone[:16], 1, 0)

        # Page 2: all other employee types show email and phone.
        else:
            self.display.showText(employee.email[:16], 0, 0)
            self.display.showText(employee.phone[:16], 1, 0)

        self.show_status_light(status)

    def show_status_light(self, status):
        if status == "Available":
            color = GREEN
        elif status == "Away":
            color = YELLOW
        else:
            color = RED

        self.lightstrip.setColor(color)


# ------------------------- NAMEPLATE CONTROLLER ----------------------

class NameplateController:
    """Coordinates employees, buttons, display, buzzer, and navigation."""

    def __init__(self, employees, view, buzzer, button_handler):
        self.employees = employees
        self.view = view
        self.buzzer = buzzer
        self.button_handler = button_handler
        self.current_index = 0
        self.current_page = 0
        self.last_page_change = time.ticks_ms()
        self.page_interval = 4000  # switch LCD page every 4 seconds

    def get_current_employee(self):
        return self.employees[self.current_index]

    def previous_employee(self):
        self.current_index = (self.current_index - 1) % len(self.employees)
        self.current_page = 0
        self.play_sound()
        self.refresh()

    def next_employee(self):
        self.current_index = (self.current_index + 1) % len(self.employees)
        self.current_page = 0
        self.play_sound()
        self.refresh()

    def change_availability(self):
        employee = self.get_current_employee()

        # Only non-administrators can manually cycle availability.
        if not isinstance(employee, Administrator):
            employee.cycle_availability()
            self.play_sound()
            self.refresh()

    def play_sound(self):
        self.buzzer.beep(880, 100)

    def refresh(self):
        employee = self.get_current_employee()
        self.view.show_employee(employee, self.current_page)
        self.last_page_change = time.ticks_ms()

    def run(self):
        self.refresh()

        while True:
            # Process button flags outside interrupt context.
            if self.button_handler.previous_pressed:
                self.button_handler.previous_pressed = False
                self.previous_employee()

            if self.button_handler.next_pressed:
                self.button_handler.next_pressed = False
                self.next_employee()

            if self.button_handler.availability_pressed:
                self.button_handler.availability_pressed = False
                self.change_availability()

            # Automatically alternate between the two LCD pages.
            now = time.ticks_ms()
            if time.ticks_diff(now, self.last_page_change) >= self.page_interval:
                self.current_page = 1 - self.current_page
                self.refresh()

            # Refresh administrator calendar status periodically.
            employee = self.get_current_employee()
            if isinstance(employee, Administrator):
                self.view.show_status_light(employee.get_availability())

            time.sleep_ms(50)


# ------------------------- HARDWARE / MAIN ---------------------------

def main():
    print("Starting Dynamic Office Nameplate...")

    # Hardware devices
    lcd = LCDDisplay(sda=LCD_SDA, scl=LCD_SCL)
    buzzer = PassiveBuzzer(pin=BUZZER_PIN, name="NameplateBuzzer")
    lightstrip = LightStrip(
        pin=LIGHTSTRIP_PIN,
        name="AvailabilityRing",
        numleds=NUMBER_OF_LEDS,
        brightness=0.35
    )

    # Sample employees (replace these examples with your own information).
    calendar = Calendar()

    employees = [
        Faculty(
            "Dr. Rivera",
            "305-555-0101",
            "Professor",
            "rivera@university.edu",
            "MIS 300",
            "OH M/W 10-12"
        ),
        Staff(
            "Jordan Lee",
            "305-555-0102",
            "Office Staff",
            "jlee@university.edu",
            "Available"
        ),
        Administrator(
            "Alex Morgan",
            "305-555-0103",
            "Administrator",
            "amorgan@university.edu",
            calendar
        ),
        StudentWorker(
            "Taylor Smith",
            "305-555-0104",
            "Student Worker",
            "tsmith@university.edu",
            "Dr. Rivera"
        )
    ]

    # Create controller and connect the three physical buttons.
    button_handler = NameplateButtonHandler()

    previous_button = Button(
        PREVIOUS_BUTTON_PIN, "previous", handler=button_handler
    )
    next_button = Button(
        NEXT_BUTTON_PIN, "next", handler=button_handler
    )
    availability_button = Button(
        AVAILABILITY_BUTTON_PIN, "availability", handler=button_handler
    )

    view = NameplateView(lcd, lightstrip)
    controller = NameplateController(
        employees, view, buzzer, button_handler
    )

    try:
        controller.run()
    except KeyboardInterrupt:
        print("Nameplate stopped.")
        lcd.clear()
        lightstrip.off()
        buzzer.stop()
        previous_button.setHandler(None)
        next_button.setHandler(None)
        availability_button.setHandler(None)


if __name__ == "__main__":
    main()
